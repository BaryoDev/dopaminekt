// Fail before any upload when a Maven Central task is scheduled without a signing key.
// publishToMavenLocal is not matched, so it keeps working unsigned.
val hasSigningKey = providers.gradleProperty("signingInMemoryKey").orNull?.isNotBlank() == true
gradle.taskGraph.whenReady {
    val central = allTasks.filter { it.name.contains("MavenCentral") }
    if (central.isNotEmpty() && !hasSigningKey) {
        throw GradleException(
            "Refusing to publish to Maven Central without a signing key (signingInMemoryKey is not set). " +
                "Scheduled: " + central.joinToString { it.path } + ". Use scripts/publish.sh."
        )
    }
}

// Writes every fixture file and the schema as Kotlin string constants, so jvm, android host
// and iOS tests read the same data with no file IO. The output lives in build/ and is not committed.
abstract class GenerateFixtureSources : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val specDir: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    // Chunks stay far below the 65535 byte limit of one JVM string constant.
    private val dollarExpr = "\${'$'}"
    private val quoteExpr = "\${'\"'}"

    private fun literal(text: String): String {
        val parts = mutableListOf<String>()
        var start = 0
        while (start < text.length) {
            var end = minOf(start + 6000, text.length)
            if (end < text.length && text[end - 1].isHighSurrogate()) end--
            parts += text.substring(start, end)
            start = end
        }
        val chunks = parts.map { chunk ->
            var body = chunk.replace("$", dollarExpr).replace("\"\"\"", "\"\"" + quoteExpr)
            if (body.endsWith("\"")) body = body.dropLast(1) + quoteExpr
            "\"\"\"" + body + "\"\"\""
        }
        return chunks.joinToString(",\n        ", prefix = "listOf(\n        ", postfix = ",\n    ).joinToString(\"\")")
    }

    @TaskAction
    fun generate() {
        val root = specDir.get().asFile
        val files = File(root, "fixtures").listFiles { f -> f.isFile && f.name.endsWith(".json") }!!.sortedBy { it.name }
        val out = StringBuilder()
        out.append("package dev.baryo.dopaminekt\n\n")
        out.append("// Generated by the generateFixtureSources Gradle task. Do not edit.\n")
        out.append("internal object FixtureData {\n")
        out.append("    val schema: String = ").append(literal(File(root, "schema.json").readText())).append("\n\n")
        out.append("    val files: Map<String, String> = mapOf(\n")
        for (file in files) {
            out.append("        \"").append(file.name).append("\" to ").append(literal(file.readText())).append(",\n")
        }
        out.append("    )\n}\n")
        val dir = File(outputDir.get().asFile, "dev/baryo/dopaminekt").apply { mkdirs() }
        File(dir, "FixtureData.kt").writeText(out.toString())
    }
}

val generateFixtureSources = tasks.register<GenerateFixtureSources>("generateFixtureSources") {
    group = "dopaminekt"
    description = "Generates a commonTest source holding spec/core fixtures as string constants."
    specDir.set(rootProject.layout.projectDirectory.dir("spec/core"))
    outputDir.set(layout.buildDirectory.dir("generated/fixtures/commonTest/kotlin"))
}

kotlin.sourceSets.commonTest {
